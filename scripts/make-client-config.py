#!/usr/bin/env python3
"""
Writes Engine.ini and Game.ini files that point a Battle Breakers client at a Breakers Revived server.

    python3 scripts/make-client-config.py http://192.168.1.20:8000 [--out client-config] [--no-unverified]

Output tree (copy each folder to the matching location on the device):

    <out>/windows/WorldExplorers/Saved/Config/WindowsNoEditor/        -> %LOCALAPPDATA%\\WorldExplorers\\Saved\\Config\\WindowsNoEditor
    <out>/android/storage/emulated/0/Android/data/com.chairentertainment.BattleBreakers/files/Saved/Config/Android/
    <out>/android/sdcard/UE4Game/WorldExplorers/Saved/Config/Android/
    <out>/android/data/data/com.chairentertainment.BattleBreakers/files/Saved/Config/Android/

The Windows and Android paths are the ones listed in README.md. Which Android path a client reads depends on its version.

Key sources:
- Confirmed: every key in res/wex/api/cloudstorage/system/DefaultEngine.ini and DefaultGame.ini. The server already
  sends these files to clients as cloud storage hotfixes, with {0} replaced by [server] domain (host:port for Engine.ini,
  full URL for Game.ini; see api/wex/cloud_storage.py). This script writes the same content locally, so the client
  reaches the server before the first hotfix download.
- Unverified: the extra per-service [OnlineSubsystemMcp.*ServiceMcp] sections appended below. Their names follow the
  usual Unreal Engine 4 OnlineSubsystemMcp layout and were not found in this repo, the docs submodule or
  Breakers-Revived/Sinum-BattleBreakers. Skip them with --no-unverified. See NOTES.md.
"""
import argparse
import sys
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = ROOT / "res" / "wex" / "api" / "cloudstorage" / "system"

WINDOWS_DIR = Path("windows/WorldExplorers/Saved/Config/WindowsNoEditor")
ANDROID_DIRS = [
    Path("android/storage/emulated/0/Android/data/com.chairentertainment.BattleBreakers/files/Saved/Config/Android"),
    Path("android/sdcard/UE4Game/WorldExplorers/Saved/Config/Android"),
    Path("android/data/data/com.chairentertainment.BattleBreakers/files/Saved/Config/Android"),
]

# UNVERIFIED section names (see module docstring and NOTES.md).
UNVERIFIED_SERVICES = [
    "LightswitchServiceMcp",
    "FriendServiceMcp",
    "PersonaServiceMcp",
    "PresenceServiceMcp",
    "EntitlementsServiceMcp",
    "CatalogServiceMcp",
    "EulaTrackingServiceMcp",
    "PriceEngineServiceMcp",
    "DataRouterServiceMcp",
]


def build_engine_ini(protocol: str, host_port: str, include_unverified: bool) -> str:
    text = (TEMPLATES / "DefaultEngine.ini").read_text(encoding="utf-8")
    # Same substitution as api/wex/cloud_storage.py: Engine.ini gets host:port only.
    text = text.replace("{0}", host_port)
    if protocol != "http":
        text = text.replace("Protocol=http", f"Protocol={protocol}")
    header = (f"; Generated by scripts/make-client-config.py for {protocol}://{host_port}\n"
              "; Confirmed keys copied from res/wex/api/cloudstorage/system/DefaultEngine.ini\n\n")
    text = header + text.rstrip() + "\n"
    if include_unverified:
        text += ("\n; ---- UNVERIFIED: per-service overrides (names from the UE4 OnlineSubsystemMcp layout, not confirmed "
                 "for Battle Breakers). Remove with --no-unverified. ----\n")
        for service in UNVERIFIED_SERVICES:
            text += f"\n[OnlineSubsystemMcp.{service}]\nProtocol={protocol}\nDomain={host_port}\n"
    return text


def build_game_ini(base_url: str) -> str:
    text = (TEMPLATES / "DefaultGame.ini").read_text(encoding="utf-8")
    # Same substitution as api/wex/cloud_storage.py: Game.ini gets the full URL.
    text = text.replace("{0}", base_url)
    header = (f"; Generated by scripts/make-client-config.py for {base_url}\n"
              "; Confirmed keys copied from res/wex/api/cloudstorage/system/DefaultGame.ini\n\n")
    return header + text.rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("server_url", help="Server URL the client should use, e.g. http://192.168.1.20:8000")
    parser.add_argument("--out", default="client-config", help="Output folder (default: client-config)")
    parser.add_argument("--no-unverified", action="store_true", help="Leave out the unverified per-service sections")
    args = parser.parse_args()

    parsed = urllib.parse.urlparse(args.server_url if "://" in args.server_url else f"http://{args.server_url}")
    if parsed.scheme not in ("http", "https") or not parsed.hostname:
        print(f"Invalid server URL: {args.server_url}", file=sys.stderr)
        return 2
    host_port = parsed.netloc
    base_url = f"{parsed.scheme}://{host_port}"
    if parsed.hostname in ("127.0.0.1", "localhost"):
        print("Note: 127.0.0.1 only works when the client runs on the same machine as the server. For an emulator, "
              "phone or VM, use the Mac's LAN address (Android emulator: http://10.0.2.2:8000).", file=sys.stderr)

    engine = build_engine_ini(parsed.scheme, host_port, not args.no_unverified)
    game = build_game_ini(base_url)
    out = Path(args.out)
    for folder in [WINDOWS_DIR, *ANDROID_DIRS]:
        (out / folder).mkdir(parents=True, exist_ok=True)
        (out / folder / "Engine.ini").write_text(engine, encoding="utf-8")
        (out / folder / "Game.ini").write_text(game, encoding="utf-8")

    print(f"Wrote Engine.ini and Game.ini for {base_url} under {out}/")
    print(f"\nWindows (CrossOver/Parallels): copy {out / WINDOWS_DIR}\\*.ini to "
          "%LOCALAPPDATA%\\WorldExplorers\\Saved\\Config\\WindowsNoEditor\\")
    print("\nAndroid (adb; the /data/data path needs a rooted device or emulator image):")
    for folder in ANDROID_DIRS:
        device_path = "/" + str(folder.relative_to("android")).replace("\\", "/")
        print(f"  adb shell mkdir -p '{device_path}'")
        print(f"  adb push '{out / folder}/Engine.ini' '{out / folder}/Game.ini' '{device_path}/'")
    print(f"\nAlso set [server] domain = \"{base_url}\" in utils/config.toml so the server's hotfix files match.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
